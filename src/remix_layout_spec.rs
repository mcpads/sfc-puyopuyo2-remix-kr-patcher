const VRAM_LEN: usize = 0x1_0000;
const CGRAM_LEN: usize = 0x200;

/// A compressed ROM stream that the discovery dump held byte-exact in VRAM.
pub struct VramStream {
    pub source_pc: usize,
    pub vram_byte: usize,
    pub decoded_len: usize,
}

const MODE_LABEL_STREAM: VramStream = VramStream {
    source_pc: 0x0F_C5FE,
    vram_byte: 0x0000,
    decoded_len: 12_800,
};
const MODE_PROMPT_STREAM: VramStream = VramStream {
    source_pc: 0x0D_B322,
    vram_byte: 0x3400,
    decoded_len: 3_072,
};
const TOKOTON_CHOICE_STREAM: VramStream = VramStream {
    source_pc: 0x0C_1C16,
    vram_byte: 0x5600,
    decoded_len: 4_608,
};
const EASY_COURSE_STREAM: VramStream = VramStream {
    source_pc: 0x0C_0669,
    vram_byte: 0x5600,
    decoded_len: 6_912,
};

impl ScreenLayout {
    pub fn streams(&self) -> &'static [VramStream] {
        match self.name {
            "mode_select" => &[MODE_LABEL_STREAM, MODE_PROMPT_STREAM],
            "solo_type" | "tokoton_option" => &[MODE_LABEL_STREAM],
            // The mouth outline and lips around the choice signs come from the
            // mode-label stream; the sign classifier reads them.
            "tokoton_play_select_original" => &[MODE_LABEL_STREAM, TOKOTON_CHOICE_STREAM],
            "easy_course_select_original" => &[MODE_LABEL_STREAM, EASY_COURSE_STREAM],
            _ => &[],
        }
    }

    fn tilemap(&self) -> Result<Vec<u8>> {
        decode_pinned(self.tilemap_hex, self.tilemap_sha256, self.name, "tilemap")
    }

    fn cgram(&self) -> Result<Vec<u8>> {
        let cgram = decode_pinned(self.cgram_hex, self.cgram_sha256, self.name, "CGRAM")?;
        if cgram.len() != CGRAM_LEN {
            bail!("{} CGRAM constant is not {CGRAM_LEN} bytes", self.name);
        }
        Ok(cgram)
    }

    fn tilemap_len(&self) -> usize {
        if self.bg1_double_width { 0x1000 } else { 0x800 }
    }

    /// Write the minimal VRAM/CGRAM/state view the label importers consume.
    /// VRAM outside the listed ROM streams and the BG1 tilemap page is zero.
    pub fn materialize(&self, rom: &[u8], dir: &Path) -> Result<()> {
        let tilemap = self.tilemap()?;
        if tilemap.len() != self.tilemap_len() {
            bail!(
                "{} tilemap constant length differs from BG1 width",
                self.name
            );
        }
        let mut vram = vec![0u8; VRAM_LEN];
        for stream in self.streams() {
            let block = crate::snes_lz::decompress(rom, stream.source_pc)
                .with_context(|| format!("decompress {} stream", self.name))?;
            if block.bytes.len() != stream.decoded_len {
                bail!(
                    "{} stream at PC 0x{:06X} decoded to {} bytes, expected {}",
                    self.name,
                    stream.source_pc,
                    block.bytes.len(),
                    stream.decoded_len
                );
            }
            vram[stream.vram_byte..stream.vram_byte + stream.decoded_len]
                .copy_from_slice(&block.bytes);
        }
        vram[self.tilemap_byte_address..self.tilemap_byte_address + tilemap.len()]
            .copy_from_slice(&tilemap);
        let state = serde_json::json!({
            "ppu.bgMode": self.bg_mode,
            "ppu.layers[0].chrAddress": self.bg1_chr_word_address,
            "ppu.layers[0].tilemapAddress": self.bg1_tilemap_word_address,
            "ppu.layers[0].doubleWidth": self.bg1_double_width,
            "ppu.layers[0].doubleHeight": self.bg1_double_height,
        });
        std::fs::create_dir_all(dir)?;
        std::fs::write(dir.join("vram.bin"), &vram)?;
        std::fs::write(dir.join("cram.bin"), self.cgram()?)?;
        std::fs::write(dir.join("state.json"), serde_json::to_vec_pretty(&state)?)?;
        Ok(())
    }

    /// Re-derive this constant set from its discovery dump.
    pub fn check_against_dump(&self, dump: &Path, rom: &[u8]) -> Result<()> {
        let vram = std::fs::read(dump.join("vram.bin"))
            .with_context(|| format!("read {} discovery VRAM", self.name))?;
        let cgram = std::fs::read(dump.join("cram.bin"))?;
        let state: serde_json::Value =
            serde_json::from_slice(&std::fs::read(dump.join("state.json"))?)?;
        if sha256(&vram) != self.discovery_vram_sha256 {
            bail!("{} discovery VRAM hash differs", self.name);
        }
        let map = &vram[self.tilemap_byte_address..self.tilemap_byte_address + self.tilemap_len()];
        if map != self.tilemap()?.as_slice() || cgram != self.cgram()? {
            bail!(
                "{} tilemap or CGRAM constant differs from its dump",
                self.name
            );
        }
        let number = |key: &str| state.get(key).and_then(serde_json::Value::as_u64);
        let boolean = |key: &str| state.get(key).and_then(serde_json::Value::as_bool);
        if number("ppu.bgMode") != Some(self.bg_mode)
            || number("ppu.layers[0].chrAddress") != Some(self.bg1_chr_word_address)
            || number("ppu.layers[0].tilemapAddress") != Some(self.bg1_tilemap_word_address)
            || boolean("ppu.layers[0].doubleWidth") != Some(self.bg1_double_width)
            || boolean("ppu.layers[0].doubleHeight") != Some(self.bg1_double_height)
        {
            bail!("{} BG1 geometry constant differs from its dump", self.name);
        }
        let referenced_tiles = map
            .as_chunks::<2>()
            .0
            .iter()
            .map(|entry| usize::from(u16::from_le_bytes(*entry) & 0x03FF))
            .collect::<std::collections::BTreeSet<_>>();
        for stream in self.streams() {
            let block = crate::snes_lz::decompress(rom, stream.source_pc)?;
            let held = vram
                .get(stream.vram_byte..stream.vram_byte + block.bytes.len())
                .with_context(|| format!("{} stream lies outside VRAM", self.name))?;
            let matches = match self.stream_check {
                StreamCheck::WholeStream => held == block.bytes.as_slice(),
                StreamCheck::ReferencedTiles => {
                    let first_tile = stream.vram_byte / 32;
                    referenced_tiles
                        .iter()
                        .filter_map(|tile| tile.checked_sub(first_tile))
                        .filter(|tile| (tile + 1) * 32 <= block.bytes.len())
                        .all(|tile| {
                            held[tile * 32..(tile + 1) * 32]
                                == block.bytes[tile * 32..(tile + 1) * 32]
                        })
                }
            };
            if !matches {
                bail!(
                    "{} dump does not hold PC 0x{:06X} at VRAM 0x{:04X}",
                    self.name,
                    stream.source_pc,
                    stream.vram_byte
                );
            }
        }
        Ok(())
    }
}

fn decode_pinned(hex: &str, expected_sha256: &str, name: &str, kind: &str) -> Result<Vec<u8>> {
    if !hex.len().is_multiple_of(2) {
        bail!("{name} {kind} constant has odd hex length");
    }
    let bytes = (0..hex.len())
        .step_by(2)
        .map(|index| u8::from_str_radix(&hex[index..index + 2], 16))
        .collect::<Result<Vec<_>, _>>()
        .with_context(|| format!("{name} {kind} constant is not hex"))?;
    if sha256(&bytes) != expected_sha256 {
        bail!("{name} {kind} constant hash differs from its pin");
    }
    Ok(bytes)
}

fn sha256(data: &[u8]) -> String {
    format!("{:x}", Sha256::digest(data))
}

